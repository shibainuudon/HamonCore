static_assert(hamon::is_same<float,       decltype(hamon::exp(0.0f))>::value, "");
static_assert(hamon::is_same<double,      decltype(hamon::exp(0.0 ))>::value, "");
static_assert(hamon::is_same<double,      decltype(hamon::exp(0   ))>::value, "");
